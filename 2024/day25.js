function parseSchematics(input) {
  const heights = [];
  for (let i = 0; i < 5; i++) {
    let count = 0;
    for (let j = 0; j < 7; j++) {
      const chunk = input[j][i];
      if (chunk === '#') count++;
    }
    heights.push(count - 1);
  }
  return [input[0][0] === "." ? 1 : 0, heights];
}

function fitLockKey(input) {
  const locks = [];
  const keys = [];
  input.map(chunk => {
    const [isKey, heights] = parseSchematics(chunk);
    if (isKey) keys.push(heights);
    else locks.push(heights);
  });
  const candidates = [];
  for (let i = 0; i < 30; i++) {
    candidates.push(new Set());
  }
  keys.forEach(key => {
    key.forEach((height, i) => {
      for (let j = 0; j < 6 - height; j++) {
        candidates[i * 6 + j].add(key);
      }
    });
  });

  return locks.reduce((sum, lock) => {
    let fit = [...candidates[lock[0]]];
    for (let i = 1; i < 5; i++) {
      fit = fit.filter(key => candidates[i * 6 + lock[i]].has(key));
    }
    return sum + fit.length;
  }, 0);
}

