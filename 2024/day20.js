function bestCheats(input, cheatTime = 2, cutoff = 100) {
  const width = input[0].length;
  const height = input.length;
  const map = new Int32Array(width * height);

  let start;

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const char = input[y][x];
      const key = y * width + x;
      map[key] = char === '#' ? -1 : 0;
      if (char === 'S') start = key;
    }
  }

  const track = traceTrack(map, width, height, start);

  let count = 0;

  for (let i = 0; i < track.length - cutoff; i++) {
    const curr = track[i];
    const x = curr % width;
    const y = Math.floor(curr / width);

    for (const [dx, dy, n] of manhattanSpiral(cheatTime)) {
      if (x + dx < 0 || x + dx >= width || y + dy < 0 || y + dy >= height) continue;
      const key = (y + dy) * width + x + dx;
      if (map[key] - map[curr] - n >= cutoff) count++;
    }
  }

  return count;
}

function traceTrack(map, width, height, start) {
  const sequence = [];
  let curr = start;
  let position = 0;
  while (true) {
    sequence.push(curr);
    map[curr] = position;
    position++;

    const x = curr % width;
    if (x > 0 && map[curr - 1] === 0) curr -= 1;
    else if (x < width - 1 && map[curr + 1] === 0) curr += 1;
    else if (curr >= width && map[curr - width] === 0) curr -= width;
    else if (curr < width * (height - 1) && map[curr + width] === 0) curr += width;
    else break;
  }
  return sequence;
}

function* manhattanSpiral(size) {
  let x = 0;
  let y = 0;
  for (let n = 1; n <= size; n++) {
    y--;
    for (let m = 0; m < n; m++) {
      x++;
      y++;
      yield [x, y, n];
    }
    for (let m = 0; m < n; m++) {
      x--;
      y++;
      yield [x, y, n];
    }
    for (let m = 0; m < n; m++) {
      x--;
      y--;
      yield [x, y, n];
    }
    for (let m = 0; m < n; m++) {
      x++;
      y--;
      yield [x, y, n];
    }
  }
}

